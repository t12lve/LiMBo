import { beforeEach, describe, expect, it, vi } from "vitest";
import { exportNetscapeCookies } from "./export-cookies";

function cookie(partial: Partial<chrome.cookies.Cookie> & { name: string; value: string }): chrome.cookies.Cookie {
  return {
    domain: "example.com",
    hostOnly: false,
    path: "/",
    secure: false,
    session: false,
    ...partial,
  } as chrome.cookies.Cookie;
}

type Query = { url?: string; domain?: string };

function mockGetAll(impl: (query: Query) => chrome.cookies.Cookie[]): void {
  (chrome.cookies as unknown as { getAll: unknown }).getAll = vi.fn(
    async (query: Query) => impl(query),
  );
}

beforeEach(() => {
  vi.clearAllMocks();
  mockGetAll(() => []);
});

describe("exportNetscapeCookies", () => {
  it("returns an empty string for a non-URL input", async () => {
    expect(await exportNetscapeCookies("not a url")).toBe("");
  });

  it("returns an empty string when there are no cookies", async () => {
    expect(await exportNetscapeCookies("https://www.youtube.com/watch?v=1")).toBe("");
  });

  it("queries the page URL, its hostname, and the parent domain", async () => {
    const calls: Query[] = [];
    mockGetAll((query) => {
      calls.push(query);
      return [];
    });

    await exportNetscapeCookies("https://www.youtube.com/watch?v=1");

    expect(calls).toEqual([
      { url: "https://www.youtube.com/watch?v=1" },
      { domain: "www.youtube.com" },
      { domain: "youtube.com" },
    ]);
  });

  it("formats a host-only secure cookie", async () => {
    mockGetAll((query) =>
      query.url
        ? [
            cookie({
              domain: "www.youtube.com",
              hostOnly: true,
              secure: true,
              name: "SID",
              value: "abc",
              expirationDate: 1_700_000_000.9,
            }),
          ]
        : [],
    );

    const lines = (await exportNetscapeCookies("https://www.youtube.com/watch?v=1")).split("\n");

    expect(lines[0]).toBe("# Netscape HTTP Cookie File");
    expect(lines[1]).toBe("# Generated by LiMBo extension");
    // expiry is floored; tab-separated, 7 columns.
    expect(lines[2]).toBe(
      ["www.youtube.com", "FALSE", "/", "TRUE", "1700000000", "SID", "abc"].join("\t"),
    );
  });

  it("keeps a leading dot and marks subdomains included; missing expiry becomes 0", async () => {
    mockGetAll((query) =>
      query.url
        ? [cookie({ domain: ".youtube.com", hostOnly: false, name: "PREF", value: "x" })]
        : [],
    );

    const out = await exportNetscapeCookies("https://youtube.com/watch?v=1");
    const row = out.split("\n")[2];

    expect(row).toBe([".youtube.com", "TRUE", "/", "FALSE", "0", "PREF", "x"].join("\t"));
  });

  it("adds a leading dot for a non-host-only cookie that lacks one", async () => {
    mockGetAll((query) =>
      query.url
        ? [cookie({ domain: "youtube.com", hostOnly: false, name: "N", value: "v" })]
        : [],
    );

    const row = (await exportNetscapeCookies("https://youtube.com/watch?v=1")).split("\n")[2];

    expect(row.startsWith(".youtube.com\tTRUE")).toBe(true);
  });

  it("de-duplicates cookies returned by more than one query", async () => {
    const shared = cookie({ domain: "youtube.com", hostOnly: true, name: "X", value: "1" });
    mockGetAll(() => [shared]);

    const out = await exportNetscapeCookies("https://youtube.com/watch?v=1");

    expect(out.split("\n").slice(2)).toHaveLength(1);
  });

  it("falls back to '/' when the cookie has no path", async () => {
    mockGetAll((query) =>
      query.url ? [cookie({ domain: "youtube.com", hostOnly: true, path: "", name: "X", value: "1" })] : [],
    );

    const row = (await exportNetscapeCookies("https://youtube.com/watch?v=1")).split("\n")[2];

    expect(row.split("\t")[2]).toBe("/");
  });
});
